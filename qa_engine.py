"""Retrieval-first question answering. LLM only ranks verified candidates by ID.
No factual string generated by a model is accepted as an answer.
"""
from __future__ import annotations
import re
from dynamic_fields import query_dynamic,tokens,STOP as STOPWORDS
from proposal_fields import query_proposal
from checkbox_fields import query_checkboxes
from extractor import answer_question

COMMON={'where','locate','found','can','i','what','which','the','me','give','show','of','is','are','in','for','this','document','pdf','number','no','value','values','tell','please','person','insured','first','second','1st','2nd','all','details','my','find','get','and','who','does','have','has'}
ID_WORDS={'pan','aadhaar','aadhar','gst','gstin','cgst','sgst','igst','abha','ifsc','tpa'}

def _normalize(s):return ' '.join(tokens(s))

def _record(r,method):
    return {'Field':r.get('Field',''),'Value':str(r.get('Value','')).strip(),'Person':r.get('Person','') or '',
            'Page':r.get('Page'),'Evidence':r.get('Evidence','') or '', 'Method':r.get('Method',method)}

def _qcontext(question):
    q=_normalize(question)
    # Person terms are filters, not fields; never infer gender from names.
    person=''
    if re.search(r'\b(second|2nd)\b',q):person='2'
    elif re.search(r'\b(first|1st)\b',q):person='1'
    return q,person

def _person_match(rec,wanted):
    if not wanted:return True
    p=str(rec.get('Person','')).lower()
    if not p:return False
    if wanted=='1':return ('1' in p or 'first' in p or 'proposer' in p)
    return ('2' in p or 'second' in p)

def _mentions_only(question, pages):
    qwords=[w for w in tokens(question) if w not in COMMON]
    if not qwords:return False
    # Check a full token sequence against source text; mentions are not evidence of a value.
    return any(all(w in tokens(t) for w in qwords) for t in pages)

def _unique(items):
    out=[]; seen=set()
    for r in items:
        k=(r['Field'].lower(),r['Value'].lower(),r['Page'],r['Person'].lower())
        if k not in seen and r['Value']:
            out.append(r); seen.add(k)
    return out

def ask(question,extracted):
    q,person=_qcontext(question)
    if not q.strip():return {'status':'empty_question','answers':[],'note':''}
    proposal=extracted.get('proposal_records',[])
    checked=extracted.get('checkbox_records',[])
    candidate=extracted.get('indexed_records',[])
    # Checked selections take precedence, never print merely available options.
    checked_hits=query_checkboxes(question,checked)
    if checked_hits:
        rows=[_record(x,'verified vector checkbox') for x in checked_hits if _person_match(x,person)]
        if rows:return {'status':'found','answers':_unique(rows),'note':'Checked options from visible vector marks. Verify against page image.'}
    # Strong template-specific verified fields.
    if proposal:
        hits=query_proposal(question,proposal)
        if person:hits=[x for x in hits if _person_match(x,person)]
        if hits:return {'status':'found','answers':_unique([_record(x,'verified template positions') for x in hits]),'note':'Template-specific structured extraction.'}
    # Structured policy schedule fields: no raw mention fallback.
    if not proposal:
        for field,info in answer_question(question,extracted):
            if isinstance(info,dict) and info.get('value') is not None:
                rows=[{'Field':field,'Value':str(info['value']),'Page':info.get('page'), 'Person':'','Evidence':info.get('evidence',''),'Method':info.get('method','structured') }]
                return {'status':'found','answers':rows,'note':'Structured policy field.'}
    # Pure general label-value candidates.
    # A field label that contains another value (e.g. 'PAN: XXXXX ...') is not a valid PAN label.
    # Regulatory/ID fields require a precise label AND a value of the right type.
    hits=query_dynamic(question,candidate)
    requested=set(tokens(question))
    if 'pan' in requested:
        hits=[h for h in hits if re.fullmatch(r'(?:proposer\s+)?pan(?:\s+(?:card|number|no))?',h.get('Field','').strip(),re.I)
              and re.fullmatch(r'[A-Z]{5}[0-9]{4}[A-Z]',str(h.get('Value','')).replace(' ',''),re.I)]
    if 'gst' in requested or 'gstin' in requested:
        if 'gstin' in requested:
            hits=[h for h in hits if 'gstin' in tokens(h.get('Field','')) and 'gst' not in tokens(h.get('Field',''))]
        else:
            hits=[h for h in hits if 'gst' in tokens(h.get('Field','')) and 'gstin' not in tokens(h.get('Field',''))]

    if person:hits=[h for h in hits if _person_match(h,person)]
    verified=[_record(h,'discovered label-value candidate') for h in hits]
    if verified:
        return {'status':'found','answers':_unique(verified),'note':'Candidate match; review source evidence.'}
    pages=extracted.get('pages',[])
    # Strictly distinguish mention with no extracted value.
    if _mentions_only(question,pages):
        return {'status':'mentioned_no_value','answers':[],'note':'Term appears in PDF, but no associated value could be reliably extracted.'}
    return {'status':'not_found','answers':[],'note':'No grounded field value found. The document may lack this field, or its layout/OCR may be unsupported.'}
